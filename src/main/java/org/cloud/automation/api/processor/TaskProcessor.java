package org.cloud.automation.api.processor;

import org.cloud.automation.api.domain.Task;

/**
 * Интерфейс для обработчиков асинхронных задач.
 * <p>
 * Каждый класс, реализующий этот интерфейс, отвечает за выполнение одного конкретного типа задач
 * (определяемого методом {@link #getType()}).
 * <p>
 * Система будет автоматически находить и вызывать нужный процессор в зависимости от типа задачи.
 */
public interface TaskProcessor {

    /**
     * Выполняет основную логику задачи.
     * Этот метод будет вызываться асинхронно. Реализация должна включать в себя обновление
     * статуса задачи (на RUNNING, SUCCESS или FAILED) и сохранение результата или ошибки.
     *
     * @param task Задача, которую необходимо выполнить.
     */
    void execute(Task task);

    /**
     * Возвращает строковый идентификатор типа задачи, который поддерживает данный процессор.
     * Это значение должно совпадать с полем {@link Task#getType()}.
     * Например: "create_ec2", "ssh_command".
     *
     * @return Тип задачи.
     */
    String getType();
}
