package org.cloud.automation.api.domain;

/**
 * Перечисление, определяющее роли пользователей в системе.
 */
public enum UserRole {
    /**
     * Представляет сотрудника поддержки или администратора.
     */
    AGENT,

    /**
     * Представляет клиента или конечного пользователя системы.
     */
    CUSTOMER
}
